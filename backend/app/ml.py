"""Phase 4: ML confidence classifier.

The model is a 3-class LogisticRegression trained offline on synthetic
data generated by running the rule-based classifier against two
canonical scans (a known-good and a known-bad username). It produces a
0-100 ``ml_confidence`` score for the CLAIMED class, which the runtime
attaches to every CheckResult.

Design notes:

- Runtime never sees scikit-learn — the trained model is exported to
  ONNX at training time (``backend/scripts/train_ml.py``) and loaded
  here through ``onnxruntime``. This keeps the production image small
  and removes a sklearn-version compatibility footgun.

- The feature set is intentionally tiny (8 floats): everything we
  already collect in the existing pipeline plus a couple of cheap
  body-shape signals. No body text is fed to the model; everything is
  numeric.

- The model is *complementary*, not authoritative. If the rule-based
  classifier says CLAIMED with confidence 92 and the ML classifier says
  18, the SPA should surface the disagreement (an ``ml-disagree``
  signal) rather than override either side.

- If the model file is missing or onnxruntime fails to load it, the
  module degrades gracefully: ``score()`` returns ``None`` and the
  runtime treats every result as "ML unavailable".
"""

from __future__ import annotations

import logging
import math
import re
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .config import settings
from .sites import Site

log = logging.getLogger(__name__)

# Order MUST stay in sync with backend/scripts/train_ml.py — the ONNX model
# encodes the column ordering, so adding/removing/reordering features
# requires re-training.
FEATURE_NAMES: tuple[str, ...] = (
    "http_status_2xx",  # 1 if 200<=status<300 else 0
    "http_status_4xx",  # 1 if 400<=status<500 else 0
    "log_body_length",  # log10(1 + len(body))
    "presence_match_count",
    "absence_match_count",
    "error_match_count",
    "log_elapsed_ms",  # log10(1 + elapsed_ms)
    "head_only_site",  # 1 if site is HEAD-only else 0
)

# Model bundle path (relative to this file). Stored under ``app/ml/`` so
# wheel-packaging picks it up automatically.
_MODEL_PATH = Path(__file__).parent / "ml" / "model.onnx"

# Word-boundary regex for cheap presence/absence string match counting.
# We tokenize on whitespace + common punctuation rather than re-running
# substring search to stay fast on long bodies.
_TOKENISER = re.compile(r"[^A-Za-z0-9_]+")


@dataclass(frozen=True, slots=True)
class FeatureVector:
    http_status_2xx: float
    http_status_4xx: float
    log_body_length: float
    presence_match_count: float
    absence_match_count: float
    error_match_count: float
    log_elapsed_ms: float
    head_only_site: float

    def to_list(self) -> list[float]:
        return [
            self.http_status_2xx,
            self.http_status_4xx,
            self.log_body_length,
            self.presence_match_count,
            self.absence_match_count,
            self.error_match_count,
            self.log_elapsed_ms,
            self.head_only_site,
        ]


def _count_substr_hits(body: str, needles: tuple[str, ...]) -> int:
    if not body or not needles:
        return 0
    return sum(1 for n in needles if n in body)


def build_features(
    site: Site,
    *,
    http_status: int | None,
    body: str,
    elapsed_ms: int | None,
) -> FeatureVector:
    """Project a primary-probe outcome into the model's feature space."""
    status_code = http_status or 0
    body_len = len(body or "")
    return FeatureVector(
        http_status_2xx=1.0 if 200 <= status_code < 300 else 0.0,
        http_status_4xx=1.0 if 400 <= status_code < 500 else 0.0,
        log_body_length=math.log10(1 + body_len),
        presence_match_count=float(_count_substr_hits(body, site.presense_strs)),
        absence_match_count=float(_count_substr_hits(body, site.absence_strs)),
        error_match_count=float(_count_substr_hits(body, site.error_strs)),
        log_elapsed_ms=math.log10(1 + (elapsed_ms or 0)),
        head_only_site=1.0 if site.head_only else 0.0,
    )


# ---------------------------------------------------------------------------
# ONNX runtime wrapper
# ---------------------------------------------------------------------------


class _ModelHandle:
    """Lazy onnxruntime ``InferenceSession`` wrapped in a thread-safe
    singleton.

    The session is process-local; we don't want to re-create it on every
    call (model load is dominated by the protobuf parse). All public
    methods are guarded with a lock because ORT sessions are
    documented-thread-safe but we still want deterministic ``run`` calls
    when the model is being reloaded after a config change.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        # onnxruntime ships no type stubs, so we keep the session as Any
        # rather than dragging in a ``TYPE_CHECKING`` import dance for a
        # third-party object that has no public class hierarchy.
        self._session: Any = None
        self._input_name: str = ""
        self._claimed_class_index: int = 0
        self._loaded = False
        self._load_error: str | None = None

    def load(self, path: Path = _MODEL_PATH) -> bool:
        with self._lock:
            if self._loaded:
                return self._session is not None
            self._loaded = True
            if not path.exists():
                self._load_error = f"model file missing: {path}"
                log.warning("phase-4 ml: %s", self._load_error)
                return False
            try:
                import onnxruntime as ort

                # Single-threaded session: per-result inference is
                # sub-millisecond and we run them inside the existing
                # asyncio thread pool, so multi-threaded ORT just costs
                # us context switches.
                opts = ort.SessionOptions()
                opts.intra_op_num_threads = 1
                opts.inter_op_num_threads = 1
                self._session = ort.InferenceSession(
                    str(path),
                    sess_options=opts,
                    providers=["CPUExecutionProvider"],
                )
                inputs = self._session.get_inputs()
                if not inputs:
                    self._load_error = "model has no inputs"
                    self._session = None
                    return False
                self._input_name = inputs[0].name
                # The probability output is the second model output by
                # convention from skl2onnx's logistic-regression
                # converter; class labels come from the first.
                outs = self._session.get_outputs()
                if len(outs) < 2:
                    self._load_error = "model missing probability output"
                    self._session = None
                    return False
                # Resolve which probability column corresponds to CLAIMED.
                # We store the class label list as ONNX metadata at
                # training time; if it's absent, default to index 1.
                meta = self._session.get_modelmeta().custom_metadata_map or {}
                claimed_idx = meta.get("claimed_class_index")
                self._claimed_class_index = int(claimed_idx) if claimed_idx else 1
                return True
            except Exception as e:  # pragma: no cover - guarded by tests
                self._load_error = f"{type(e).__name__}: {e}"
                log.warning("phase-4 ml: failed to load model: %s", self._load_error)
                self._session = None
                return False

    def is_available(self) -> bool:
        if not self._loaded:
            self.load()
        return self._session is not None

    def claimed_probability(self, features: FeatureVector) -> float | None:
        if not self.is_available():
            return None
        try:
            import numpy as np

            x = np.array([features.to_list()], dtype=np.float32)
            with self._lock:
                # ``run(None, ...)`` returns all outputs in declaration order.
                outputs = self._session.run(None, {self._input_name: x})
            # The probability output is a list-of-dicts (one dict per
            # input row) in skl2onnx's default format. Normalise to a
            # float in [0, 1] for the CLAIMED class.
            probs = outputs[1]
            if isinstance(probs, list) and probs and isinstance(probs[0], dict):
                # Try integer key first, fall back to label.
                row = probs[0]
                for key in (
                    self._claimed_class_index,
                    str(self._claimed_class_index),
                    "claimed",
                    1,
                ):
                    if key in row:
                        return float(row[key])
                return None
            # Numpy ndarray fallback (some versions of ORT inline the dict).
            if hasattr(probs, "shape"):
                arr = probs
                if arr.ndim == 2 and arr.shape[1] > self._claimed_class_index:
                    return float(arr[0][self._claimed_class_index])
            return None
        except Exception as e:  # pragma: no cover - guarded by tests
            log.warning("phase-4 ml: scoring failed: %s", e)
            return None


_HANDLE = _ModelHandle()


def is_model_available() -> bool:
    """True iff the ONNX model is loadable and ready to score."""
    return _HANDLE.is_available()


def score(
    site: Site,
    *,
    http_status: int | None,
    body: str,
    elapsed_ms: int | None,
) -> int | None:
    """Run a probe outcome through the ML classifier.

    Returns the CLAIMED-class probability mapped to ``0-100``, or
    ``None`` if the model is unavailable or the rule-based classifier
    explicitly opted out (e.g. SKIPPED results, where features are
    meaningless).
    """
    if not settings.enable_ml_confidence:
        return None
    handle = _HANDLE
    if not handle.is_available():
        return None
    features = build_features(
        site,
        http_status=http_status,
        body=body,
        elapsed_ms=elapsed_ms,
    )
    proba = handle.claimed_probability(features)
    if proba is None:
        return None
    # Clamp to integer 0-100. We round to nearest to keep the SPA's
    # "ml 73" pill stable across small numeric jitter.
    return max(0, min(100, round(proba * 100)))


def reset_model_handle_for_tests() -> None:
    """Drop the cached session so tests can swap in a new model file."""
    global _HANDLE
    _HANDLE = _ModelHandle()
